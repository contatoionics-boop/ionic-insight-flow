-- Catálogo de produtos ativos (código + nome) para o usuário buscar e inserir nas tabelas do documento.
-- Carga inicial a partir do relatório "Produtos Ativos" do portal, enquanto não há integração com o Protheus.
-- Quando a integração existir, ela grava nesta mesma tabela (origem = 'protheus').
CREATE TABLE IF NOT EXISTS public.produtos_catalogo (
  codigo text PRIMARY KEY,
  nome text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  origem text NOT NULL DEFAULT 'planilha',
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS produtos_catalogo_nome_idx ON public.produtos_catalogo (lower(nome));

GRANT SELECT ON public.produtos_catalogo TO authenticated;
GRANT ALL ON public.produtos_catalogo TO service_role;

ALTER TABLE public.produtos_catalogo ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Autenticados podem buscar produtos" ON public.produtos_catalogo;
CREATE POLICY "Autenticados podem buscar produtos"
ON public.produtos_catalogo FOR SELECT TO authenticated
USING (ativo);

